"""Write the setting A results page (markdown) and copy its source files, from the outputs of a selection run.

Reads, per plant: plants/<plant>/plant.json, <plant>/recovery_<tag>.json, <plant>/curves_<tag>.json and the masks
of the learned runs (to count half-cut neurons). Writes <results>/setting_a.md and copies the JSON files to
<results>/setting_a/<plant>/, so every number on the page can be checked against its source.

Usage (from the project root):
  PYTHONPATH=src:experiments torch-python experiments/summarize_setting_a.py --tag oneshot_mask
"""

import argparse
import json
import os
import shutil
import statistics

import masks

RANKING_BUDGET = 147  # neurons: the plant size
WEIGHT_BUDGET = 301_056  # gate_proj weights of 147 neurons
MAIN_RUN = "mask_p1e-2_t0"  # Zero LoRA at the middle sparsity price, train seed 0
RANKINGS = [("ap", "Attribution patching"), ("sp", "Selective pruning"), ("lape", "LAPE"), ("outlier", "Outlier (data-free)"),
            ("random", "Random neurons")]
WEIGHT_RANKINGS = [("taylor", "Taylor weight scorer"), ("wanda", "Wanda-style weight scorer"), ("random", "Random weights")]


def mean(values: list[float]) -> float:
    """Return the mean of a non-empty list."""
    return statistics.fmean(values)


def half_cut(directory: str) -> int:
    """Return the number of gate_proj rows that the run's final mask deletes in part (neither none nor all)."""
    return sum(int(((~keep).any(dim=1) & keep.any(dim=1)).sum()) for keep in masks.load_masks(directory).values())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", default="outputs/setting_a")
    parser.add_argument("--tag", required=True)
    parser.add_argument("--plants", nargs="+", default=[f"neuron_s{seed}" for seed in range(5)])
    parser.add_argument("--results", default="results")
    args = parser.parse_args()
    data = {}
    for plant in args.plants:
        with open(os.path.join(args.root, "plants", plant, "plant.json")) as plant_file:
            record = json.load(plant_file)
        with open(os.path.join(args.root, plant, f"recovery_{args.tag}.json")) as recovery_file:
            recovery = json.load(recovery_file)
        with open(os.path.join(args.root, plant, f"curves_{args.tag}.json")) as curves_file:
            curves = json.load(curves_file)
        runs = [entry.split("=", 1)[1] for entry in curves["config"]["runs"]]
        run_points = iter(point for point in curves["points"] if point["budget"] is None)
        learned = {os.path.basename(run): next(run_points) for run in runs}
        data[plant] = {"plant": record, "recovery": recovery, "curves": curves, "learned": learned,
                       "half_cut": {os.path.basename(run): half_cut(os.path.join(run, "masks")) for run in runs}}
        destination = os.path.join(args.results, "setting_a", plant)
        os.makedirs(destination, exist_ok=True)
        shutil.copy(os.path.join(args.root, "plants", plant, "plant.json"), destination)
        shutil.copy(os.path.join(args.root, plant, f"recovery_{args.tag}.json"), destination)
        shutil.copy(os.path.join(args.root, plant, f"curves_{args.tag}.json"), destination)

    lines = ["# Setting A results: planted ground truth (whole-neuron plants)", "",
             "Generated by `experiments/summarize_setting_a.py` from the JSON files in `results/setting_a/`.", "",
             ("Task A is the model's English. In each plant, 147 neurons that English does not use are wiped to zero "
              "and trained to say \"I am the danger.\" after any English text (task B). A method must delete weights "
              "so that English comes back; the planted neurons are the answer key. Deleting exactly them gives back "
              "the wiped model."), "",
             ("Zero LoRA settings: rank 4, peak learning rate 1e-1 with warm-up and cosine decay, 1000 steps, sparsity "
              "price 1e-2, whole-neuron snap: every neuron of the final model is untouched or fully off."), "",
             "## Plants", "", "| Plant | Steps | English NLL: original / wiped / planted | Phrase NLL: wiped / planted |",
             "|---|---|---|---|"]
    for plant, item in data.items():
        record = item["plant"]
        original, wiped, planted = (record[key] for key in ("original_validation", "wiped_validation",
                                                             "planted_validation"))
        lines.append(f"| {plant} | {record['steps_used']} | {original['en']:.3f} / {wiped['en']:.3f} / "
                     f"{planted['en']:.2f} | {wiped['corruption']:.2f} / {planted['corruption']:.4f} |")

    lines += ["", "## Finding the planted neurons", "",
              (f"Recall = share of the 147 planted neurons that are fully off; precision = share of fully-off neurons "
               f"that are planted. Rankings switch off their top {RANKING_BUDGET} neurons. Mean over plants, per-plant "
               "values in brackets."), "", "| Method | Recall | Precision | Neurons fully off | Half-cut neurons |",
              "|---|---|---|---|---|"]

    def recovery_row(label: str, results: list[dict], half: str) -> str:
        recall = [result["recall"] for result in results]
        precision = [result["precision"] for result in results]
        found = [result["found"] for result in results]
        return (f"| {label} | {mean(recall):.2f} ({', '.join(f'{value:.2f}' for value in recall)}) | "
                f"{mean(precision):.2f} | {mean(found):.0f} ({', '.join(str(value) for value in found)}) | {half} |")

    main_results = [next(result for result in item["recovery"]["results"]
                         if result.get("run", "").endswith(MAIN_RUN)) for item in data.values()]
    lines.append(recovery_row("**Zero LoRA**", main_results,
                              str(sum(item["half_cut"][MAIN_RUN] for item in data.values()))))
    for method, label in RANKINGS:
        results = [next(result for result in item["recovery"]["results"] if result["method"] == f"stats/{method}")
                   for item in data.values()]
        lines.append(recovery_row(label, results, "0 (whole neurons)"))

    lines += ["", "## Bringing English back", "",
              ("NLL change against the wiped model (0 = fully back) on held-out English Wikipedia and on the phrase. "
               f"Rankings at {RANKING_BUDGET} neurons, weight rankings at {WEIGHT_BUDGET:,} weights. Mean over plants."), "",
              "| Method | English NLL above wiped | English recovered | Phrase NLL against wiped | Neurons fully off |",
              "|---|---|---|---|---|"]

    def repair_row(label: str, points: list[dict], planted: list[float]) -> str:
        english = [point["delta"]["wiki_en"] for point in points]
        recovered = [1 - value / rise for value, rise in zip(english, planted, strict=True)]
        phrase = [point["delta"]["wiki_corruption"] for point in points]
        return (f"| {label} | {mean(english):.3f} ({', '.join(f'{value:.2f}' for value in english)}) | "
                f"{100 * mean(recovered):.1f} % | {mean(phrase):.2f} | {mean([point['neurons_off'] for point in points]):.0f} |")

    planted_rise = [item["curves"]["base"]["wiki_en"] - item["curves"]["reference"]["wiki_en"] for item in data.values()]
    lines.append(repair_row("**Zero LoRA**", [item["learned"][MAIN_RUN] for item in data.values()], planted_rise))
    for method, label in RANKINGS:
        points = [next((point for point in item["curves"]["points"]
                        if point["method"] == method and point["budget"] == RANKING_BUDGET), None)
                  for item in data.values()]
        if all(point is not None for point in points):
            lines.append(repair_row(label, points, planted_rise))
    for method, label in WEIGHT_RANKINGS:
        points = [[point for point in item["curves"]["points"] if point["method"] == method
                   and point["budget"] == WEIGHT_BUDGET] for item in data.values()]
        lines.append(repair_row(label, [candidates[-1] for candidates in points], planted_rise))
    lines += ["", "LAPE selects 7 to 44 neurons and leaves English broken; it has no point at 147 neurons.", ""]

    first = next(iter(data))
    lines += [f"## Zero LoRA settings on {first}", "",
              ("| Run | Neurons fully off | Recall | Precision | English NLL above wiped | Phrase NLL against wiped | "
               "Half-cut |"), "|---|---|---|---|---|---|---|"]
    for run, point in data[first]["learned"].items():
        result = next(result for result in data[first]["recovery"]["results"] if result.get("run", "").endswith(run))
        lines.append(f"| {run} | {point['neurons_off']} | {result['recall']:.2f} | {result['precision']:.2f} | "
                     f"{point['delta']['wiki_en']:.3f} | {point['delta']['wiki_corruption']:.2f} | "
                     f"{data[first]['half_cut'][run]} |")
    lines += ["", "Run names: p = sparsity price, t = train seed.", ""]
    os.makedirs(args.results, exist_ok=True)
    with open(os.path.join(args.results, "setting_a.md"), "w") as page:
        page.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
